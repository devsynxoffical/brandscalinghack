export const ogImageFor = (path) => OG_IMAGES[path] || DEFAULT_OG_IMAGE;

const breadcrumb = (items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, path], i) => ({
    '@type': 'ListItem',
    position: i + 1,
    name,
    item: `${BASE_URL}${path}`
  }))
});

const faqPage = (id, faqs) => ({
  '@type': 'FAQPage',
  '@id': `${BASE_URL}${id}`,
  mainEntity: faqs.map((f) => ({
    '@type': 'Question',
    name: f.question,
    acceptedAnswer: { '@type': 'Answer', text: f.answer }
  }))
});

const webPage = ({ path, type = 'WebPage', name, description, speakable, extra = {} }) => ({
  '@type': type,
  '@id': `${BASE_URL}${path}#webpage`,
  url: `${BASE_URL}${path === '/' ? '/' : path}`,
  name,
  description,
  isPartOf: { '@id': WEBSITE_ID },
  about: { '@id': ORG_ID },
  primaryImageOfPage: { '@type': 'ImageObject', url: ogImageFor(path) },
  inLanguage: 'en-US',
  ...(speakable ? { speakable: { '@type': 'SpeakableSpecification', cssSelector: speakable } } : {}),
  ...extra
});

