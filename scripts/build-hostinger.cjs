// Writes dist/.htaccess so the built site runs on Hostinger (Apache / LiteSpeed) the same way it
// ran on Vercel: same 301 redirects (from vercel.json), www + https, no trailing slashes,
// prerendered pages served from <path>/index.html, real 404 status, headers and caching.
// Run after `npm run build`: node scripts/build-hostinger.cjs
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const vercel = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));
const dist = path.join(root, 'dist');
if (!fs.existsSync(path.join(dist, 'index.html'))) throw new Error('Run npm run build first');

const esc = (s) => s.replace(/[.+?^$()[\]{}|\\]/g, '\\$&');
const redirectLines = [];
for (const r of vercel.redirects || []) {
  if (r.has) continue; // host redirect handled below
  let src = r.source.replace(/^\//, '');
  let dest = r.destination;
  if (src.includes(':')) {
    // "/case/:id" -> ^case/([^/]+)$ -> /cases/$1
    let n = 0;
    const names = [];
    src = src.split('/').map((seg) => {
      if (seg.startsWith(':')) { names.push(seg.slice(1).replace(/\*$/, '')); n++; return seg.endsWith('*') ? '(.*)' : '([^/]+)'; }
      return esc(seg);
    }).join('/');
    names.forEach((name, i) => { dest = dest.replace(new RegExp(`:${name}\\*?`), `$${i + 1}`); });
  } else {
    src = esc(src);
  }
  redirectLines.push(`RewriteRule ^${src}/?$ ${dest} [R=301,L,NE]`);
}

const htaccess = `# Generated by scripts/build-hostinger.cjs from vercel.json. Do not edit by hand.
Options -MultiViews -Indexes
DirectorySlash Off
DirectoryIndex index.html
ErrorDocument 404 /404.html

AddType application/xml .xml
AddType application/rss+xml .rss
AddType text/plain .txt
AddType video/mp4 .mp4
AddType image/webp .webp
AddType image/svg+xml .svg
AddType application/manifest+json .webmanifest
AddDefaultCharset utf-8

<IfModule mod_rewrite.c>
RewriteEngine On

# https and www (one hop)
RewriteCond %{HTTP_HOST} ^brandscalinghacks\\.com$ [NC,OR]
RewriteCond %{HTTP_HOST} ^www\\.brandscalinghacks\\.com$ [NC]
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^brandscalinghacks\\.com$ [NC]
RewriteRule ^(.*)$ https://www.brandscalinghacks.com/$1 [R=301,L,NE]

# old URLs (${redirectLines.length} redirects from vercel.json)
${redirectLines.join('\n')}

# no trailing slash (as on Vercel)
RewriteCond %{REQUEST_URI} ^/(.+)/$
RewriteRule ^ /%1 [R=301,L,NE]

# prerendered pages: /about -> /about/index.html
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{DOCUMENT_ROOT}/$1/index.html -f
RewriteRule ^(.+)$ /$1/index.html [L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
<FilesMatch "\\.(html)$">
Header set Cache-Control "public, max-age=0, must-revalidate"
</FilesMatch>
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType text/css "access plus 1 year"
ExpiresByType application/javascript "access plus 1 year"
ExpiresByType text/javascript "access plus 1 year"
ExpiresByType image/webp "access plus 1 year"
ExpiresByType image/jpeg "access plus 1 year"
ExpiresByType image/png "access plus 1 year"
ExpiresByType image/svg+xml "access plus 1 year"
ExpiresByType video/mp4 "access plus 1 year"
ExpiresByType font/woff2 "access plus 1 year"
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/rss+xml application/javascript text/javascript application/json image/svg+xml
</IfModule>
`;
fs.writeFileSync(path.join(dist, '.htaccess'), htaccess);
// Netlify-style SPA fallback file would be served as a plain file on Apache; not needed.
fs.rmSync(path.join(dist, '_redirects'), { force: true });
console.log(`dist/.htaccess written: ${redirectLines.length} redirects`);
