// Writes src/data/contentIndex.js: the small per-page index (path, kind, title, description,
// headline) for the data-driven content pages. The app shell uses it for routing, <head> tags
// and hub listings, so the full page copy in src/data/pages/*.js can load as a separate chunk.
// Runs at the start of `npm run build`; commit the output so `npm run dev` works too.
const fs = require('fs');
const path = require('path');

(async () => {
  const { CONTENT_PAGES } = await import('../src/data/pageRegistry.js');
  const index = CONTENT_PAGES.map((p) => ({
    path: p.path,
    kind: p.kind,
    titleTag: p.titleTag,
    metaDescription: p.metaDescription,
    h1: p.h1,
    eyebrow: p.eyebrow || null
  }));
  const out = `// GENERATED by scripts/generate-content-index.cjs from src/data/pageRegistry.js. Do not edit.\nexport const CONTENT_INDEX = ${JSON.stringify(index, null, 2)};\n\nconst BY_PATH = new Map(CONTENT_INDEX.map((p) => [p.path, p]));\nexport const contentIndexByPath = (p) => BY_PATH.get(p) || null;\nexport const contentIndexOfKind = (kind) => CONTENT_INDEX.filter((p) => p.kind === kind);\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'contentIndex.js'), out, 'utf8');
  console.log(`Content index written: ${index.length} pages.`);

  // Route metadata for the app shell (titles, descriptions, canonicals, robots), so App.jsx does
  // not need to import every blog post and case study just to set <head> tags.
  const { blogPosts } = await import('../src/data/blogPosts.js');
  const { allCaseStudies } = await import('../src/data/allCaseStudies.js');
  const { allCaseSeo } = await import('../src/data/caseFacts.js');
  const { isNoindexCase, canonicalCasePath } = await import('../src/data/caseIndexing.js');
  const { CASE_NICHES } = await import('../src/data/caseNiches.js');
  const seoMap = allCaseSeo(allCaseStudies);
  const blog = Object.fromEntries(blogPosts.map((p) => [p.slug, [p.titleTag, p.metaDescription]]));
  const cases = {};
  for (const cs of allCaseStudies) {
    const seo = seoMap.get(cs.slug || cs.id);
    const row = [seo.titleTag, seo.metaDescription, canonicalCasePath(cs), isNoindexCase(cs) ? 1 : 0, cs.image || ''];
    for (const k of [cs.slug, cs.id, cs.shortcode]) if (k && !cases[k]) cases[k] = row;
  }
  const niches = Object.fromEntries(CASE_NICHES.map((n) => [n.slug, [n.titleTag, n.metaDescription]]));
  const meta = `// GENERATED by scripts/generate-content-index.cjs. Do not edit.\n// [titleTag, metaDescription] per blog post and case niche; cases add [canonicalPath, noindex, image].\nexport const BLOG_META = ${JSON.stringify(blog)};\nexport const CASE_META = ${JSON.stringify(cases)};\nexport const NICHE_META = ${JSON.stringify(niches)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'routeMeta.js'), meta, 'utf8');
  console.log(`Route meta written: ${blogPosts.length} posts, ${allCaseStudies.length} cases, ${CASE_NICHES.length} niches.`);
})().catch((e) => { console.error(e); process.exit(1); });
