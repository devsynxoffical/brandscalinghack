// Reads duration and dimensions of every case study video with ffprobe and writes
// src/data/caseVideoMeta.js (committed), used for VideoObject structured data.
// Re-run after adding videos: npm run video-meta  (needs ffprobe locally)
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

(async () => {
  const { allCaseStudies } = await import('../src/data/allCaseStudies.js');
  const out = {};
  for (const cs of allCaseStudies) {
    if (!cs.videoUrl || cs.videoType === 'image') continue;
    const file = path.join(__dirname, '..', 'public', cs.videoUrl);
    if (!fs.existsSync(file)) continue;
    const raw = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'format=duration:stream=width,height', '-of', 'json', file]).toString();
    const j = JSON.parse(raw);
    const seconds = Math.round(parseFloat(j.format.duration));
    const st = (j.streams && j.streams[0]) || {};
    out[cs.videoUrl] = { seconds, width: st.width || null, height: st.height || null };
  }
  const body = `// Generated by scripts/generate-video-meta.cjs. Do not edit by hand.\nexport const CASE_VIDEO_META = ${JSON.stringify(out, null, 2)};\n\nexport const isoDuration = (s) => {\n  const m = Math.floor(s / 60);\n  const sec = s % 60;\n  return \`PT\${m ? m + 'M' : ''}\${sec}S\`;\n};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'caseVideoMeta.js'), body);
  console.log(`Video meta written for ${Object.keys(out).length} videos.`);
})();
